// Run against a built local app. API writes are intercepted; no user data changes.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const PNG=fs.readFileSync(path.resolve(__dirname,'../../backend/demo_photos/demo-repair.png')).toString('base64');
const BEFORE=fs.readFileSync(path.resolve(__dirname,'../../backend/demo_photos/demo-road-condition.png')).toString('base64');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try { for(const width of [1440,390]) {
  const context=await browser.newContext({viewport:{width,height:900},permissions:['geolocation'],geolocation:{latitude:44.848,longitude:65.482,accuracy:10}});
  const page=await context.newPage();page.setDefaultTimeout(12000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const user={id:'review-inspector',role:'inspector',name:'Тест инспектора',email:'test@example.invalid'};
  const now=new Date().toISOString();
  const section={id:'review-route',name:'Тестовый маршрут',code:'TEST',length_km:2,geometry:{type:'LineString',coordinates:[[65.482,44.848],[65.49,44.86]]},inspector_id:user.id,inspector_name:user.name,notes:'',state:'assigned',duration_min:5,source:'demo'};
  const contractorPhoto={id:'contractor-repair-photo',url:`data:image/png;base64,${PNG}`,name:'После ремонта.png'};
  const inspectorPhoto={id:'inspector-control-photo',url:`data:image/png;base64,${PNG}`,name:'Контрольный осмотр.png'};
  const report=()=>({id:'review-report',created_at:now,comment:'Покрытие восстановлено',photos:[contractorPhoto],decision:null,decision_comment:null});
  const defect={id:'review-defect',number:'TEST-001',section_id:section.id,inspection_id:null,type:'Выбоина',description:'Проверка ремонта',status:'review',lat:44.848,lng:65.482,location_source:'gps',accuracy_m:10,observed_at:now,received_at:now,inspector_id:user.id,contractor_id:'test-contractor',contractor_name:'Тест подрядчика',due_at:null,overdue:false,version:1,photos:[{id:'before-photo',url:`data:image/png;base64,${BEFORE}`,name:'До ремонта.png'}],repairs:[report()],history:[]};
  let published=false;const actions=[];let uploads=0;
  await page.route('**/api/**',async r=>{
   const u=new URL(r.request().url()).pathname;let body;
   if(u==='/api/health')body={ok:true,demo:true};
   else if(u==='/api/notifications')body=[];
   else if(u==='/api/me')body=user;
   else if(u==='/api/bootstrap')body={user,sections:[section],contractors:[],inspectors:[user]};
   else if(u==='/api/inspections')body=[];
   else if(u==='/api/files'&&r.request().method()==='POST'){uploads++;body=inspectorPhoto;}
   else if(u==='/api/defects')body=published?[defect]:[];
   else if(u==='/api/defects/'+defect.id)body=defect;
   else if(u.endsWith('/actions')){
    const data=r.request().postDataJSON();actions.push(data);
    assert.equal(data.version,defect.version);
    assert.ok(['reject','approve'].includes(data.action));
    if(data.action==='reject')assert.equal(Object.hasOwn(data,'review_evidence'),false,'rejection must not require acceptance evidence');
    if(data.action==='approve'){
     const evidence=data.review_evidence;assert.ok(evidence,'approval must submit review evidence');
     assert.deepEqual(evidence.photo_ids,['inspector-control-photo']);
     assert.deepEqual(evidence.checklist,{surface_restored:true,no_visible_damage:true,area_safe:true});
     assert.equal(typeof evidence.lat,'number');assert.equal(typeof evidence.lng,'number');assert.equal(evidence.accuracy_m,10);
     const age=Date.now()-Date.parse(evidence.recorded_at);assert.ok(Number.isFinite(age)&&age>=-5000&&age<=30000,'evidence timestamp must be a fresh GPS fix');
     defect.repairs.at(-1).review_evidence={photos:[inspectorPhoto],inspector_id:user.id,checked_at:new Date().toISOString(),distance_m:0,...evidence};
    }
    defect.status=data.action==='approve'?'closed':'rework';defect.version++;
    defect.repairs.at(-1).decision=data.action==='approve'?'accepted':'rejected';
    defect.repairs.at(-1).decision_comment=data.comment||null;body=defect;
   }else throw new Error('Unexpected request '+u);
   await r.fulfill({json:body});
  });
  await page.goto(process.env.APP_URL||'http://127.0.0.1:8000',{waitUntil:'domcontentloaded'});
  await page.locator('.inspector-workspace:not([inert])').waitFor();
  const navigation=page.locator(width>700?'.inspector-desktop-nav':'.inspector-mobile-nav');
  const review=navigation.getByRole('button',{name:/Проверка работ/});
  assert.ok(await review.isVisible());const box=await review.boundingBox();assert.ok(box.y>=0&&box.y+box.height<=900,'review is in initial viewport');
  await review.click();await page.getByText('Нет работ на проверке',{exact:true}).waitFor();
  published=true;await page.getByRole('button',{name:'Обновить',exact:true}).click();
  await page.locator('.inspector-defect-row').waitFor();assert.match(await review.innerText(),/1/);
  await page.locator('.inspector-defect-row').click();
  const approve=page.locator('.rr-actions .button.primary');await approve.waitFor();
  await page.locator('.photo-zoom-trigger').first().click();
  const photoDialog=page.getByRole('dialog',{name:'Просмотр фотографии'});await photoDialog.waitFor();
  await photoDialog.getByRole('slider').fill('3');
  assert.equal(await photoDialog.locator('.photo-viewer-image img').evaluate(img=>img.style.width),'300%');
  await page.keyboard.press('Escape');await photoDialog.waitFor({state:'hidden'});
  assert.equal(await approve.isDisabled(),true,'approval starts disabled without inspector control photos and checklist');
  const reject=page.getByRole('button',{name:'Вернуть на доработку',exact:true});assert.equal(await reject.isDisabled(),true);
  await page.locator('.rr-comment-field textarea').fill('Исправить край покрытия');await reject.click();
  await page.locator('.alert.success').filter({hasText:'Работа отправлена на доработку.'}).waitFor();
  assert.equal(actions[0].comment,'Исправить край покрытия');
  await review.click();await page.getByText('Нет работ на проверке',{exact:true}).waitFor();
  defect.status='review';defect.version++;defect.repairs=[report()];await page.getByRole('button',{name:'Обновить',exact:true}).click();
  await page.locator('.inspector-defect-row').click();await approve.waitFor();
  assert.equal(await approve.isDisabled(),true,'approval remains disabled before a control photo is uploaded');
  await page.locator('.rr-upload input[type="file"]').first().setInputFiles({name:'control.png',mimeType:'image/png',buffer:Buffer.from(PNG,'base64')});
  await page.getByText('Фото «control.png» загружено',{exact:true}).waitFor();assert.equal(uploads,1);
  assert.equal(await approve.isDisabled(),true,'photo alone is not enough to accept');
  const checklist=page.locator('.rr-checklist input[type="checkbox"]');
  await page.locator('.rr-check').nth(0).click();await page.locator('.rr-check').nth(1).click();
  assert.equal(await checklist.nth(0).isChecked(),true);assert.equal(await checklist.nth(1).isChecked(),true);
  assert.equal(await approve.isDisabled(),true,'all checklist items are required');
  await page.locator('.rr-check').nth(2).click();assert.equal(await checklist.nth(2).isChecked(),true);
  await page.waitForFunction(()=>{const button=[...document.querySelectorAll('.rr-actions button')].find(item=>item.textContent.includes('Принять ремонт'));return !!button&&!button.disabled;});
  await context.clearPermissions();
  await page.locator('.rr-gps-wait').waitFor();assert.equal(await approve.isDisabled(),true,'approval requires a fresh GPS position');
  await context.grantPermissions(['geolocation']);
  await context.setGeolocation({latitude:44.848,longitude:65.482,accuracy:10});
  await page.locator('.rr-gps-live').waitFor();
  await page.waitForFunction(()=>{const button=[...document.querySelectorAll('.rr-actions button')].find(item=>item.textContent.includes('Принять ремонт'));return !!button&&!button.disabled;});
  const screenshotDir=path.resolve(__dirname,'../../docs/screenshots/routes');fs.mkdirSync(screenshotDir,{recursive:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'no horizontal overflow');
  await page.screenshot({path:path.join(screenshotDir,`repair-review-${width}.png`),fullPage:true});
  await page.locator('.rr-comment-field textarea').fill('Проверено на месте');await approve.click();
  await page.locator('.alert.success').filter({hasText:'Дефект принят и закрыт.'}).waitFor();
  assert.equal(actions[1].action,'approve');assert.equal(actions[1].comment,'Проверено на месте');
  assert.match(await page.locator('.rr-stored-evidence').innerText(),/Материалы проверки инспектора/);
  await review.click();await page.getByText('Нет работ на проверке',{exact:true}).waitFor();
  defect.status='review';defect.version++;defect.repairs=[];await page.getByRole('button',{name:'Обновить',exact:true}).click();
  await page.locator('.inspector-defect-row').click();await page.getByText('Отчёт подрядчика отсутствует',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Принять ремонт',exact:true}).count(),0);
  assert.deepEqual(errors,[]);console.log(JSON.stringify({width,passed:true,actions:actions.map(a=>a.action),uploads,errors}));
  await context.close();
 }}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
